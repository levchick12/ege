data = '9 лет 16 лет 13   лет 1год'
pattern = r'\d{1,2} *(лет|год)'
print(*finditer(pattern, data))

# Метасимволы
# /d - любая цифра от 0 до 9;
# /D - любая НЕ цифра;
# /s  -любой пробельный символ;
# /S - любой не пробельный символ;
# /w - любая цифра, буква или _;
# . - любой 1 символ;

# [0-9] - любая цифра от 0 до 9;
# [a-z] - любая строчная буква латинского алфавита;
# [A-Z] - любая заглавная буква латинского алфавита;
# [0-9a-zA-Z]
# [а-яё] - кириллица;
# ^ - исключающий символ;
# [^0-9] - любой символ, но не цифра;

# Квантификаторы
# Количество символов можно указывать в виде диапазона «{m, n}»,
# что будет значить от m до n повторений предыдущего символа включительно;
# * - {0,}
# + - {1,}
# ? - {0,1}

# Скобочные группы
